# generate vectors s the trap interrupt entry points
# there has to be one entry point per interrupt number
# since otherwise theres no way for trap to discover
# the interrupt number

my $wide = @ARGV && $ARGV[0] eq "64";
my $push = $wide ? "pushq" : "pushl";
my $pointer = $wide ? ".quad" : ".long";

print "# generated by vectors.pl - do not edit\n";
print "# handlers\n";
print ".globl alltraps\n";
for(my $i = 0; $i < 256; $i++){
    print ".globl vector$i\n";
    print "vector$i:\n";
    if(!($i == 8 || ($i >= 10 && $i <= 14) || $i == 17 || ($wide && ($i == 21 || $i == 29 || $i == 30)))){
        print "  $push \$0\n";
    }
    print "  $push \$$i\n";
    print "  jmp alltraps\n";
}

print "\n# vector table\n";
print ".data\n";
print ".globl vectors\n";
print "vectors:\n";
for(my $i = 0; $i < 256; $i++){
    print "  $pointer vector$i\n";
}

